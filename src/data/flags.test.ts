import { readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { FLAGS } from "./flags";
import { getSovereignStates } from "./loadCountries";

describe("bundled flags (flag-icons, generated by scripts/build-flags.mjs)", () => {
  const states = getSovereignStates();

  it("has exactly one flag for each of the 195 sovereign states", () => {
    expect(Object.keys(FLAGS).sort()).toEqual(states.map((c) => c.code).sort());
  });

  it("is self-contained, inert SVG: a viewBox, no script, no event handlers, nothing fetched", () => {
    for (const [code, svg] of Object.entries(FLAGS)) {
      expect(svg.startsWith("<svg"), code).toBe(true);
      expect(svg, code).toMatch(/viewBox="0 0 640 480"/);
      expect(svg, code).not.toMatch(/<script|\son[a-z]+=|<foreignObject/i);
      expect(svg, code).not.toMatch(/(?:href|src)="(?:https?:)?\/\//i);
    }
  });

  it("keeps the library's MIT notice in the generated file", () => {
    const source = readFileSync(path.join(__dirname, "flags.ts"), "utf8");
    expect(source).toContain("from flag-icons 7.6.0");
    expect(source).toContain("Copyright (c) 2013 Panayiotis Lipiridis");
    expect(source).toContain("Permission is hereby granted, free of charge");
  });

  it("has current designs where flags changed recently", () => {
    // Syria (2025): green over white over black, with three red stars. (The old flag was red
    // over white over black with two green stars: the same two colors, so check the top band.)
    expect(FLAGS.SYR).toContain('<path fill="#007a3d" d="M0 0h640v160H0Z"/>');
    expect(FLAGS.SYR.match(/fill="#ce1126" d="([^"]*)"/)![1].match(/M/gi)).toHaveLength(3);
  });
});
