// Builds src/data/flags.ts: one optimized SVG flag per sovereign state, keyed by cca3.
//   - source: flag-icons (MIT, 4:3 flags), a dev dependency; the game never fetches flags
//   - each SVG is minified with SVGO (path precision checked by eye on the most detailed emblems)
//   - the flag's ISO alpha-2 code comes from countries.json's altSpellings
// The output is a plain module the game imports on demand, so all 195 flags arrive in one
// build file that the service worker caches for offline play.
// Run: npm run build:flags
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { optimize } from "svgo";

const require = createRequire(import.meta.url);
const FLAGS_DIR = join(dirname(require.resolve("flag-icons/package.json")), "flags", "4x3");
const LICENSE = await readFile(join(dirname(require.resolve("flag-icons/package.json")), "LICENSE"), "utf8");
const { version } = JSON.parse(await readFile(require.resolve("flag-icons/package.json"), "utf8"));
/** Decimal places kept in path data. Emblems are often drawn in scaled-down coordinates, so this stays at 2. */
const PRECISION = Number(process.env.FLAG_PRECISION ?? 2);
const COUNTRIES = new URL("../src/data/countries.json", import.meta.url);
const OUT = new URL("../src/data/flags.ts", import.meta.url);

const countries = JSON.parse(await readFile(COUNTRIES, "utf8"));
const isSovereign = (c) => c.unMember === true || c.cca3 === "VAT" || c.cca3 === "PSE";
const states = countries.filter(isSovereign).sort((a, b) => a.cca3.localeCompare(b.cca3));
if (states.length !== 195) throw new Error(`Expected 195 sovereign states, got ${states.length}`);

const flags = {};
let raw = 0;
let out = 0;
for (const c of states) {
  const alpha2 = (c.altSpellings ?? []).find((a) => /^[A-Z]{2}$/.test(a));
  if (!alpha2) throw new Error(`No ISO alpha-2 code for ${c.cca3}`);
  const source = await readFile(join(FLAGS_DIR, `${alpha2.toLowerCase()}.svg`), "utf8");
  const { data } = optimize(source, {
    multipass: true,
    plugins: [
      {
        name: "preset-default",
        params: { overrides: { convertPathData: { floatPrecision: PRECISION }, cleanupNumericValues: { floatPrecision: PRECISION } } },
      },
      "removeDimensions",
    ],
  });
  if (!data.includes("viewBox")) throw new Error(`${c.cca3}: optimized SVG lost its viewBox`);
  flags[c.cca3] = data;
  raw += source.length;
  out += data.length;
}

const header = [
  `// Generated by scripts/build-flags.mjs from flag-icons ${version} (4:3 flags), optimized with SVGO.`,
  "// Do not edit by hand: run `npm run build:flags`. Keyed by cca3.",
  "//",
  ...LICENSE.trim()
    .split("\n")
    .map((line) => `// ${line}`.trimEnd()),
  "",
].join("\n");
await writeFile(
  OUT,
  `${header}\n/** SVG markup of each sovereign state's flag, keyed by cca3. */\nexport const FLAGS: Readonly<Record<string, string>> = ${JSON.stringify(flags, null, 0)};\n`,
);
console.log(`${states.length} flags: ${Math.round(raw / 1024)} KB -> ${Math.round(out / 1024)} KB`);
